@dataclass
class StagePlan:
    stage_index: int
    npc_ratio: float
    npc_sequences: int
    replay_sequences: int
    total_sequences: int
    batches: int


@dataclass
class StageSchedule:
    domains: np.ndarray  # 1=NPC, 0=replay
    indices: np.ndarray
    plan: StagePlan
    batch_size: int

    def batch_slice(
        self,
        batch_index: int,
    ) -> Tuple[np.ndarray, np.ndarray]:
        start = batch_index * self.batch_size
        end = min(
            start + self.batch_size,
            self.plan.total_sequences,
        )

        return self.domains[start:end], self.indices[start:end]


def make_replay_starts(
    count: int,
    num_starts: int,
    seed: int,
) -> np.ndarray:
    if count <= 0:
        return np.empty((0,), dtype=np.int64)

    rng = np.random.default_rng(seed)

    if count <= num_starts:
        return rng.choice(
            num_starts,
            size=count,
            replace=False,
        ).astype(np.int64)

    cycles = count // num_starts
    remainder = count % num_starts
    parts: List[np.ndarray] = []

    for _ in range(cycles):
        parts.append(rng.permutation(num_starts).astype(np.int64))

    if remainder:
        parts.append(
            rng.choice(
                num_starts,
                size=remainder,
                replace=False,
            ).astype(np.int64)
        )

    return np.concatenate(parts)


def build_stage_schedule(
    *,
    stage_index: int,
    npc_ratio: float,
    npc_count: int,
    replay_num_starts: int,
    batch_size: int,
    seed: int,
) -> StageSchedule:
    if npc_ratio >= 1.0:
        replay_count = 0
    else:
        replay_count = int(
            round(
                npc_count
                * (1.0 - npc_ratio)
                / npc_ratio
            )
        )

    rng = np.random.default_rng(
        seed + 100_003 * (stage_index + 1)
    )

    npc_indices = rng.permutation(npc_count).astype(np.int64)

    replay_indices = make_replay_starts(
        count=replay_count,
        num_starts=replay_num_starts,
        seed=seed + 800_009 * (stage_index + 1),
    )

    domains = np.concatenate(
        [
            np.ones(npc_count, dtype=np.uint8),
            np.zeros(replay_count, dtype=np.uint8),
        ]
    )

    rng.shuffle(domains)

    indices = np.empty(
        (npc_count + replay_count,),
        dtype=np.int64,
    )

    npc_positions = np.flatnonzero(domains == 1)
    replay_positions = np.flatnonzero(domains == 0)

    indices[npc_positions] = npc_indices

    if replay_count:
        indices[replay_positions] = replay_indices

    total = npc_count + replay_count

    plan = StagePlan(
        stage_index=stage_index,
        npc_ratio=npc_ratio,
        npc_sequences=npc_count,
        replay_sequences=replay_count,
        total_sequences=total,
        batches=math.ceil(total / batch_size),
    )

    return StageSchedule(
        domains=domains,
        indices=indices,
        plan=plan,
        batch_size=batch_size,
    )


