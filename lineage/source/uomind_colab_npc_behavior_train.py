def benchmark_batch(
    *,
    model: UOMindLM,
    batch_size: int,
    amp_dtype: torch.dtype,
    warmup: int = 1,
    measured: int = 3,
) -> Tuple[float, float]:
    device = torch.device("cuda")
    wrapper = SequenceBalancedLoss(model)

    x = torch.randint(
        0,
        model.config.vocab_size,
        (batch_size, model.config.max_seq_len),
        dtype=torch.long,
        device=device,
    )

    y = torch.full_like(x, -100)

    # Approximate an 80/20 mix of output-masked NPC rows and full-LM replay.
    npc_rows = int(round(batch_size * 0.8))
    y[:npc_rows, -24:] = torch.randint(
        0,
        model.config.vocab_size,
        (npc_rows, 24),
        dtype=torch.long,
        device=device,
    )

    if npc_rows < batch_size:
        y[npc_rows:] = torch.randint(
            0,
            model.config.vocab_size,
            (batch_size - npc_rows, model.config.max_seq_len),
            dtype=torch.long,
            device=device,
        )

    scaler = make_grad_scaler(amp_dtype)

    torch.cuda.empty_cache()
    torch.cuda.reset_peak_memory_stats()

    started = None

    for index in range(warmup + measured):
        model.zero_grad(set_to_none=True)

        with amp_context(amp_dtype):
            loss = wrapper(x, y)

        scaler.scale(loss).backward()

        if index == warmup - 1:
            torch.cuda.synchronize()
            started = time.perf_counter()

    torch.cuda.synchronize()

    elapsed = max(1e-9, time.perf_counter() - started)
    throughput = measured * x.numel() / elapsed
    peak_gib = torch.cuda.max_memory_allocated() / 2**30

    model.zero_grad(set_to_none=True)
    del x, y, scaler, wrapper
    gc.collect()
    torch.cuda.empty_cache()

    return throughput, peak_gib


def choose_batch_size(
    *,
    model: UOMindLM,
    requested: str,
    candidates: Sequence[int],
    amp_dtype: torch.dtype,
    max_memory_fraction: float,
) -> int:
    if requested != "auto":
        value = int(requested)
        if value <= 0:
            raise ValueError("batch size must be positive")
        return value

    total_gib = torch.cuda.get_device_properties(0).total_memory / 2**30
    allowed = total_gib * max_memory_fraction

    print(
        f"Autotuning batch size; benchmark peak must stay <= {allowed:.2f} GiB...",
        flush=True,
    )

    results: Dict[int, Tuple[float, float]] = {}

    for batch in candidates:
        try:
            throughput, peak = benchmark_batch(
                model=model,
                batch_size=batch,
                amp_dtype=amp_dtype,
            )

            safe = peak <= allowed

            print(
                f"  batch={batch:4d}: {throughput:,.0f} tok/s | "
                f"peak={peak:.2f} GiB | {'safe' if safe else 'too close'}",
                flush=True,
            )

            if safe:
                results[batch] = (throughput, peak)

        except torch.OutOfMemoryError:
            print(f"  batch={batch:4d}: OOM", flush=True)
            model.zero_grad(set_to_none=True)
            gc.collect()
            torch.cuda.empty_cache()

        except RuntimeError as exc:
            if "out of memory" in str(exc).lower():
                print(f"  batch={batch:4d}: OOM", flush=True)
                model.zero_grad(set_to_none=True)
                gc.collect()
                torch.cuda.empty_cache()
            else:
                raise

    if not results:
        raise RuntimeError(
            "No safe batch size found. Supply a smaller --batch-candidates list."
        )

    winner = max(
        results,
        key=lambda batch: results[batch][0],
    )

    print(
        f"Selected batch size {winner} "
        f"({results[winner][0]:,.0f} benchmark tok/s).",
        flush=True,
    )

    return winner


def maybe_compile(
    wrapper: SequenceBalancedLoss,
    enabled: bool,
    mode: str,
):
    if not enabled:
        print("torch.compile disabled.", flush=True)
        return wrapper, False

    print(
        f"Compiling model+balanced-loss graph with torch.compile(mode={mode!r})...",
        flush=True,
    )

    try:
        compiled = torch.compile(
            wrapper,
            mode=mode,
            dynamic=False,
        )
        return compiled, True
    except Exception as exc:
        print(
            f"torch.compile failed; using eager: {type(exc).__name__}: {exc}",
            flush=True,
        )
        return wrapper, False


