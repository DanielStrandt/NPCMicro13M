_MOJIBAKE_REPLACEMENTS = {
    "â": "—",
    "â": "–",
    "â": "’",
    "â": "‘",
    "â": "“",
    "â": "”",
    "â¦": "…",
    "Â ": " ",
    "Â": "",
}


def repair_mojibake(text: str) -> str:
    for bad, good in _MOJIBAKE_REPLACEMENTS.items():
        text = text.replace(bad, good)
    return text


def read_text_robust(path: Path) -> str:
    raw = path.read_bytes()

    for encoding in (
        "utf-8-sig",
        "utf-8",
        "cp1252",
        "latin-1",
    ):
        try:
            return repair_mojibake(raw.decode(encoding))
        except UnicodeDecodeError:
            continue

    raise RuntimeError(f"could not decode {path}")


def split_story_file(path: Path) -> List[str]:
    text = read_text_robust(path)
    text = text.replace("\r\n", "\n").replace("\r", "\n").strip()

    if not text:
        return []

    blocks = [
        block.strip()
        for block in re.split(r"\n\s*\n+", text)
        if block.strip()
    ]

    if len(blocks) <= 1:
        lines = [
            line.strip()
            for line in text.splitlines()
            if line.strip()
        ]

        if len(lines) > 1:
            blocks = lines

    return [
        re.sub(r"\s+", " ", block).strip()
        for block in blocks
        if block.strip()
    ]


def pack_uo_replay_if_needed(
    *,
    workspace: Path,
    uo_dir: Path,
    tokenizer: Tokenizer,
) -> Dict[str, object]:
    # Prefer the exact packed corpus from the prior UO curriculum.
    meta_path = workspace / "uo_curriculum" / "uo_corpus_meta.json"

    if meta_path.exists():
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        train_path = Path(meta["train_bin"])
        val_path = (
            Path(meta["validation_bin"])
            if meta.get("validation_bin")
            else None
        )

        if train_path.exists() and int(meta["train_tokens"]) * 2 == train_path.stat().st_size:
            if (
                int(meta.get("validation_tokens", 0)) == 0
                or (
                    val_path is not None
                    and val_path.exists()
                    and int(meta["validation_tokens"]) * 2 == val_path.stat().st_size
                )
            ):
                print(
                    "Using packed UO train/validation corpus from prior curriculum.",
                    flush=True,
                )
                return meta

    files = sorted(uo_dir.rglob("*.txt"))

    if not files:
        raise FileNotFoundError(
            f"No UO .txt files found under {uo_dir} and no packed UO corpus exists."
        )

    print(
        "Prior packed UO corpus unavailable; rebuilding replay corpus from UO stories.",
        flush=True,
    )

    output_dir = workspace / "npc_behavior"
    output_dir.mkdir(parents=True, exist_ok=True)

    train_path = output_dir / "uo_replay_train.bin"
    val_path = output_dir / "uo_replay_validation.bin"

    all_train: List[str] = []
    all_val: List[str] = []

    for file_index, path in enumerate(files):
        stories = split_story_file(path)
        indices = list(range(len(stories)))
        rng = random.Random(7000 + file_index)
        rng.shuffle(indices)
        val_count = max(1, int(round(len(stories) * 0.05)))
        val_set = set(indices[:val_count])

        all_train.extend(
            story
            for i, story in enumerate(stories)
            if i not in val_set
        )
        all_val.extend(
            story
            for i, story in enumerate(stories)
            if i in val_set
        )

    eos_id = tokenizer.token_to_id("<EOS>")

    def pack(stories: Sequence[str], path: Path) -> int:
        temp = path.with_suffix(path.suffix + ".tmp")
        token_count = 0

        with temp.open("wb", buffering=8 * 1024 * 1024) as handle:
            for start in range(0, len(stories), 1024):
                encodings = tokenizer.encode_batch(list(stories[start:start + 1024]))
                flat: List[int] = []

                for encoding in encodings:
                    flat.extend(encoding.ids)
                    flat.append(eos_id)

                array = np.asarray(flat, dtype=np.uint16)
                array.tofile(handle)
                token_count += int(array.size)

        temp.replace(path)
        return token_count

    train_tokens = pack(all_train, train_path)
    val_tokens = pack(all_val, val_path)

    meta = {
        "train_bin": str(train_path),
        "validation_bin": str(val_path),
        "train_tokens": train_tokens,
        "validation_tokens": val_tokens,
    }

    (output_dir / "uo_replay_meta.json").write_text(
        json.dumps(meta, indent=2),
        encoding="utf-8",
    )

    return meta


class RandomWindowCorpus:
    """Flat UO token stream supporting arbitrary overlapping T+1 windows."""

    def __init__(
        self,
        path: Path,
        token_count: int,
        seq_len: int,
        keep_in_ram: bool = True,
    ) -> None:
        self.path = Path(path)
        self.token_count = int(token_count)
        self.seq_len = int(seq_len)

        mapped = np.memmap(
            self.path,
            mode="r",
            dtype=np.uint16,
            shape=(self.token_count,),
        )

        if keep_in_ram:
            self.data = np.asarray(mapped).copy()
            del mapped
        else:
            self.data = mapped

        self.num_starts = self.token_count - self.seq_len

        if self.num_starts <= 0:
            raise ValueError("replay corpus is too small")

    def gather_into(
        self,
        starts: np.ndarray,
        x_dest: np.ndarray,
        y_dest: np.ndarray,
        rows: np.ndarray,
    ) -> None:
        if starts.size == 0:
            return

        # UO corpus is small enough to keep in RAM. Gather arbitrary overlapping
        # windows without creating a corpus-sized Python example list.
        offsets = np.arange(
            self.seq_len,
            dtype=np.int64,
        )

        x_indices = starts[:, None] + offsets[None, :]
        y_indices = x_indices + 1

        x_dest[rows, :] = self.data[x_indices]
        y_dest[rows, :] = self.data[y_indices].astype(np.int16)


class FixedBlockCorpus:
    def __init__(
        self,
        path: Path,
        token_count: int,
        seq_len: int,
    ) -> None:
        self.path = Path(path)
        self.token_count = int(token_count)
        self.seq_len = int(seq_len)

        self.data = np.memmap(
            self.path,
            mode="r",
            dtype=np.uint16,
            shape=(self.token_count,),
        )

        self.num_blocks = (
            self.token_count - 1
        ) // self.seq_len

        itemsize = np.dtype(np.uint16).itemsize

        self.windows = np.lib.stride_tricks.as_strided(
            self.data,
            shape=(
                self.num_blocks,
                self.seq_len + 1,
            ),
            strides=(
                self.seq_len * itemsize,
                itemsize,
            ),
            writeable=False,
        )

    def gather_into(
        self,
        indices: np.ndarray,
        x_dest: np.ndarray,
        y_dest: np.ndarray,
        rows: np.ndarray,
    ) -> None:
        if indices.size == 0:
            return

        selected = self.windows[indices]
        x_dest[rows, :] = selected[:, :self.seq_len]
        y_dest[rows, :] = selected[:, 1:].astype(np.int16)


