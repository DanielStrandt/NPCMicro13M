#!/usr/bin/env python3
"""
uomind_colab_npc_behavior_train.py

Standalone Colab continuation trainer for the UO-Mind NPC behavior phase.

This is intended to run after:
  1. TinyStories pretraining
  2. UO story curriculum/domain adaptation

Default source checkpoint:
    /content/uomind_tinystories/uo_curriculum/checkpoints/best_uo.pt

Default tokenizer:
    /content/uomind_tinystories/tokenizer.json

Default UO story folder:
    /content/uo_stories

What this module does
---------------------
1. Loads the exact pretrained tokenizer and best UO-domain checkpoint.
2. Validates the reserved <R00> ... <R31> control tokens.
3. Generates a large deterministic structured NPC corpus locally.
4. Encodes every NPC example to a static 128-token sequence.
5. Supervises ONLY the answer region:
       <ACTION> <Rxx> <TONE> <Rxx> <SAY> ... <EOS>
6. Replays real UO-story language-model windows during behavior tuning.
7. Uses sequence-balanced loss so a replay row with 128 labels does not
   outweigh an NPC row with only ~10-30 answer labels.
8. Uses BF16 automatically on A100-class GPUs, otherwise FP16 AMP.
9. Autotunes batch size for the actual GPU.
10. Uses fused AdamW and optional torch.compile.
11. Evaluates NPC behavior + UO story retention + TinyStories retention.
12. Saves every stage, best NPC, best balanced, latest, and final checkpoints.

Default behavior curriculum
---------------------------
Each stage consumes every synthetic NPC training example exactly once.
The percentage below is the percentage of ROWS / sequence-level loss weight:

    Stage 1: 70% NPC / 30% UO-story replay
    Stage 2: 80% NPC / 20% UO-story replay
    Stage 3: 90% NPC / 10% UO-story replay
    Stage 4: 95% NPC /  5% UO-story replay

The replay windows are sampled from overlapping positions in the real UO story
corpus, not only from the ~810 non-overlapping blocks. This gives far more
variety while preserving the original UO prose distribution.

Default generated dataset
-------------------------
    200,000 NPC training examples
     20,000 held-out NPC validation examples

Task families:
    commerce
    gatekeeping
    threat
    truth/deception
    obligation/favor
    three-turn memory
    quest handling
    healing/service
    rumor/secrecy
    crime/witness
    faction/social access
    tavern/service

Run
---
    !python uomind_colab_npc_behavior_train.py

Useful overrides
----------------
    !python uomind_colab_npc_behavior_train.py --train-examples 300000
    !python uomind_colab_npc_behavior_train.py --npc-ratios 0.75,0.85,0.95
    !python uomind_colab_npc_behavior_train.py --batch-size 512
    !python uomind_colab_npc_behavior_train.py --no-compile

Notes
-----
- The model remains a causal language model; this is not a classifier head.
- The compact control language is generated by the model itself and can later
  be parsed by the game runtime before exposing only <SAY> text to players.
- No chain-of-thought is trained or exposed.
"""

