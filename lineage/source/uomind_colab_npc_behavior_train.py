def main() -> None:
    args = parse_args()

    if not torch.cuda.is_available():
        raise RuntimeError("CUDA GPU is required")

    if args.train_examples <= 0 or args.validation_examples <= 0:
        raise ValueError("example counts must be positive")

    torch.backends.cudnn.benchmark = True
    torch.backends.cuda.matmul.allow_tf32 = True
    torch.set_float32_matmul_precision("high")

    set_seed(args.seed)

    device = torch.device("cuda")
    amp_dtype = choose_amp_dtype()

    workspace = Path(args.workspace)
    output_dir = (
        Path(args.output_dir)
        if args.output_dir
        else workspace / "npc_behavior"
    )

    output_dir.mkdir(parents=True, exist_ok=True)

    print("Runtime", flush=True)
    print("-------", flush=True)
    print(f"torch:     {torch.__version__}", flush=True)
    print(f"cuda:      {torch.version.cuda}", flush=True)
    print(f"gpu:       {torch.cuda.get_device_name(0)}", flush=True)
    print(f"memory:    {gpu_memory_line()}", flush=True)
    print(f"precision: {str(amp_dtype).replace('torch.', '')}", flush=True)
    print()

    checkpoint_path = find_checkpoint(
        requested=args.checkpoint,
        workspace=workspace,
    )

