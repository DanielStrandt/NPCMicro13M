    print(f"preview:             {output_dir / 'npc_examples_preview.txt'}", flush=True)
    print()

    uo_meta = pack_uo_replay_if_needed(
        workspace=workspace,
        uo_dir=Path(args.uo_dir),
        tokenizer=tokenizer,
    )

    train(
        args=args,
        model=model,
        model_config=model_config,
        tokenizer=tokenizer,
        tokenizer_path=tokenizer_path,
        source_checkpoint=checkpoint_path,
        npc_meta=npc_meta,
        uo_meta=uo_meta,
        workspace=workspace,
        output_dir=output_dir,
        amp_dtype=amp_dtype,
    )


