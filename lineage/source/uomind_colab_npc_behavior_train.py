    def commerce(self) -> NPCExample:
        name, location, persona, voice, relation = self.common("merchant")
        role = self.choice(("blacksmith", "merchant", "tailor", "carpenter"))
        item = self.choice(ITEMS)
        floor_price = self.randint(20, 120)
        ask_price = floor_price + self.randint(5, 45)
        offer = self.randint(max(5, floor_price - 45), ask_price + 20)
        greed = self.randint(0, 2)
        insulted = int(self.coin(0.20))
        last_offer = max(1, offer - self.randint(0, 20))

        effective_floor = (
            floor_price
            + 5 * greed
            + 6 * insulted
            - 3 * max(0, relation)
        )

        if offer >= ask_price or offer >= effective_floor:
            action = "ACCEPT"
            speech = (
                f"Aye. {offer} gold, and the {item} is thine."
            )
        elif offer >= max(5, effective_floor - 20):
            action = "COUNTER"
            counter = max(
                offer + 1,
                effective_floor,
            )
            speech = (
                f"Nay. {counter} gold, and not a coin less."
            )
        else:
            action = "REFUSE"
            speech = (
                "Keep thy coin. I will not sell it for that."
            )

        player = self.choice(
            (
                f"I offer {offer} gold for the {item}.",
                f"Take {offer} gold and give me the {item}.",
                f"Will {offer} gold buy the {item}?",
            )
        )

        return self.format_example(
            task="commerce",
            role=role,
            name=name,
            location=location,
            persona=persona,
            voice=voice,
            relation=relation,
            state_fields=(
                f"item={item}",
                f"ask={ask_price}",
                f"floor={floor_price}",
                f"offer={offer}",
                f"greed={greed}",
            ),
            memory=f"insult={insulted};last_offer={last_offer}",
            player=player,
            action=action,
            speech=speech,
        )

