def train(
    *,
    args: argparse.Namespace,
    model: UOMindLM,
    model_config: ModelConfig,
    tokenizer: Tokenizer,
    tokenizer_path: Path,
    source_checkpoint: Path,
    npc_meta: NPCDatasetMeta,
    uo_meta: Dict[str, object],
    workspace: Path,
    output_dir: Path,
    amp_dtype: torch.dtype,
) -> Dict[str, object]:
    device = torch.device("cuda")

    npc_train = NPCArrayDataset(
        input_path=Path(npc_meta.train_inputs),
        label_path=Path(npc_meta.train_labels),
        task_path=Path(npc_meta.train_tasks),
        count=npc_meta.train_examples,
        seq_len=model_config.max_seq_len,
        keep_in_ram=args.npc_in_ram,
    )

    npc_val = NPCArrayDataset(
        input_path=Path(npc_meta.validation_inputs),
        label_path=Path(npc_meta.validation_labels),
        task_path=Path(npc_meta.validation_tasks),
        count=npc_meta.validation_examples,
        seq_len=model_config.max_seq_len,
        keep_in_ram=True,
    )

    replay = RandomWindowCorpus(
        path=Path(uo_meta["train_bin"]),
        token_count=int(uo_meta["train_tokens"]),
        seq_len=model_config.max_seq_len,
        keep_in_ram=True,
    )

    uo_val: Optional[FixedBlockCorpus] = None

    if int(uo_meta.get("validation_tokens", 0)) > model_config.max_seq_len:
        uo_val = FixedBlockCorpus(
            path=Path(uo_meta["validation_bin"]),
            token_count=int(uo_meta["validation_tokens"]),
            seq_len=model_config.max_seq_len,
        )

    tiny_val: Optional[FixedBlockCorpus] = None
    tiny_meta_path = workspace / "corpus_meta.json"

    if tiny_meta_path.exists():
        try:
            tiny_meta = json.loads(tiny_meta_path.read_text(encoding="utf-8"))
            tiny_val_path = Path(tiny_meta["validation_bin"])

            if tiny_val_path.exists():
                tiny_val = FixedBlockCorpus(
                    path=tiny_val_path,
                    token_count=int(tiny_meta["validation_tokens"]),
                    seq_len=model_config.max_seq_len,
                )
        except Exception:
            tiny_val = None

    checkpoint_dir = output_dir / "checkpoints"
    checkpoint_dir.mkdir(parents=True, exist_ok=True)

    latest_path = checkpoint_dir / "latest.pt"
    best_npc_path = checkpoint_dir / "best_npc.pt"
    best_balanced_path = checkpoint_dir / "best_balanced.pt"
    final_path = checkpoint_dir / "final.pt"
    history_path = output_dir / "training_history.json"

    # Discover a resume checkpoint BEFORE autotuning. Resumed runs must reuse
    # the exact static batch size that created the saved schedule/compiled graph.
    resume_payload = None

    if args.resume == "auto" and latest_path.exists():
        resume_payload = torch.load(
            latest_path,
            map_location="cpu",
            weights_only=False,
        )
    elif args.resume not in {"auto", "none"}:
        resume_path = Path(args.resume)
        resume_payload = torch.load(
            resume_path,
            map_location="cpu",
            weights_only=False,
        )

    if resume_payload is not None:
        saved_resume_config = resume_payload.get("training_config", {})
        batch_size = int(saved_resume_config["batch_size"])
        print(
            f"Resume checkpoint locks batch size to {batch_size}; "
            "skipping batch autotune.",
            flush=True,
        )
    else:
        candidates = [
            int(part.strip())
            for part in args.batch_candidates.split(",")
            if part.strip()
        ]

        batch_size = choose_batch_size(
            model=model,
            requested=args.batch_size,
            candidates=candidates,
            amp_dtype=amp_dtype,
            max_memory_fraction=args.max_memory_fraction,
        )

    ratios = parse_fractions(args.npc_ratios)

    plans: List[StagePlan] = []

    for stage_index, ratio in enumerate(ratios):
        if ratio >= 1.0:
            replay_count = 0
        else:
            replay_count = int(
                round(
                    npc_train.count
                    * (1.0 - ratio)
                    / ratio
                )
            )

        total = npc_train.count + replay_count

        plans.append(
            StagePlan(
                stage_index=stage_index,
                npc_ratio=ratio,
                npc_sequences=npc_train.count,
                replay_sequences=replay_count,
                total_sequences=total,
                batches=math.ceil(total / batch_size),
            )
        )

    total_steps = sum(plan.batches for plan in plans)

    print()
    print("NPC behavior curriculum", flush=True)
    print("-----------------------", flush=True)
    print(f"NPC train examples: {npc_train.count:,}", flush=True)
    print(f"NPC val examples:   {npc_val.count:,}", flush=True)
    print(f"UO replay starts:   {replay.num_starts:,}", flush=True)
    print(f"batch size:         {batch_size:,}", flush=True)
    print(f"precision:          {str(amp_dtype).replace('torch.', '')}", flush=True)

    for plan in plans:
        actual = plan.npc_sequences / plan.total_sequences
        print(
            f"Stage {plan.stage_index + 1}: "
            f"NPC={actual * 100:5.2f}% | "
            f"NPC rows={plan.npc_sequences:,} | "
            f"UO replay rows={plan.replay_sequences:,} | "
            f"batches={plan.batches:,}",
            flush=True,
        )

    print(f"Total steps:        {total_steps:,}", flush=True)
    print()

    optimizer = build_optimizer(
        model=model,
        lr=args.lr,
        weight_decay=args.weight_decay,
    )

    scaler = make_grad_scaler(amp_dtype)

    training_config = {
        "source_checkpoint": str(source_checkpoint),
        "tokenizer": str(tokenizer_path),
        "dataset_fingerprint": dataset_fingerprint(
            tokenizer_path=tokenizer_path,
            train_examples=npc_meta.train_examples,
            validation_examples=npc_meta.validation_examples,
            seed=npc_meta.seed,
        ),
        "npc_ratios": list(ratios),
        "batch_size": batch_size,
        "seq_len": model_config.max_seq_len,
        "lr": args.lr,
        "min_lr": args.min_lr,
        "warmup_fraction": args.warmup_fraction,
        "weight_decay": args.weight_decay,
        "grad_clip": args.grad_clip,
        "precision": str(amp_dtype),
        "total_steps": total_steps,
        "train_examples": npc_train.count,
        "validation_examples": npc_val.count,
        "sequence_balanced_loss": True,
        "control_initialization": args.init_controls,
        "forgetting_penalty": args.forgetting_penalty,
    }

    state: Dict[str, object] = {
        "stage_index": 0,
        "batch_in_stage": 0,
        "global_step": 0,
        "real_rows_seen": 0,
        "npc_rows_seen": 0,
        "replay_rows_seen": 0,
        "best_npc_loss": float("inf"),
        "best_balanced_score": float("inf"),
        "baseline_uo_loss": None,
    }

    history: List[Dict[str, object]] = []

    if resume_payload is not None:
        print(
            f"Resuming NPC behavior training from "
            f"{latest_path if args.resume == 'auto' else args.resume}",
            flush=True,
        )

        saved_config = resume_payload.get("training_config", {})

        if saved_config.get("dataset_fingerprint") != training_config["dataset_fingerprint"]:
            raise RuntimeError(
                "Resume checkpoint was built with a different synthetic NPC dataset."
            )

        if tuple(saved_config.get("npc_ratios", ())) != tuple(ratios):
            raise RuntimeError("Resume curriculum ratios do not match.")

        if int(saved_config.get("batch_size", -1)) != batch_size:
            raise RuntimeError(
                "Resume batch size differs. Re-run with "
                f"--batch-size {saved_config.get('batch_size')}"
            )

        model.load_state_dict(
            resume_payload["model_state_dict"],
            strict=True,
        )

        optimizer.load_state_dict(
            resume_payload["optimizer_state_dict"]
        )

        optimizer_to_device(optimizer, device)
        scaler.load_state_dict(
            resume_payload.get("scaler_state_dict", {})
        )

        state.update(resume_payload["state"])
        history = list(resume_payload.get("history", []))
        restore_rng(resume_payload)

    elif args.init_controls:
        initialize_control_embeddings(model, tokenizer)

    # Baseline validation AFTER optional control-token initialization. Control
    # rows were previously unused; this does not alter ordinary text tokens.
    if int(state["global_step"]) == 0:
        print()
        print("Pre-behavior validation baseline:", flush=True)

        npc_baseline = evaluate_npc(
            model=model,
            dataset=npc_val,
            batch_size=min(args.val_batch_size, batch_size),
            device=device,
            amp_dtype=amp_dtype,
            max_batches=args.npc_val_batches,
        )

        print(
            f"  NPC val: loss={npc_baseline['loss']:.4f} "
            f"ppl={npc_baseline['ppl']:.2f} "
            f"token_acc={npc_baseline['token_accuracy'] * 100:.2f}% "
            f"exact={npc_baseline['exact_accuracy'] * 100:.2f}%",
            flush=True,
        )

        uo_baseline = None

        if uo_val is not None:
            uo_baseline = evaluate_lm_corpus(
                model=model,
                corpus=uo_val,
                batch_size=min(args.val_batch_size, batch_size),
                max_batches=args.uo_val_batches,
                device=device,
                amp_dtype=amp_dtype,
            )

            state["baseline_uo_loss"] = uo_baseline["loss"]

            print(
                f"  UO story val: loss={uo_baseline['loss']:.4f} "
                f"ppl={uo_baseline['ppl']:.3f}",
                flush=True,
            )

        tiny_baseline = None

        if tiny_val is not None:
            tiny_baseline = evaluate_lm_corpus(
                model=model,
                corpus=tiny_val,
                batch_size=min(args.val_batch_size, batch_size),
                max_batches=args.tiny_val_batches,
                device=device,
                amp_dtype=amp_dtype,
            )

            print(
                f"  TinyStories val: loss={tiny_baseline['loss']:.4f} "
                f"ppl={tiny_baseline['ppl']:.3f}",
                flush=True,
            )

        history.append(
            {
                "event": "baseline",
                "global_step": 0,
                "npc_validation": npc_baseline,
                "uo_validation": uo_baseline,
                "tiny_validation": tiny_baseline,
                "geometry": model.geometry_gain_summary(),
            }
        )

        history_path.write_text(
            json.dumps(history, indent=2),
            encoding="utf-8",
        )

    wrapper = SequenceBalancedLoss(model)

    use_compile = (
        not args.no_compile
        and total_steps >= args.compile_min_steps
    )

    if not use_compile and not args.no_compile:
        print(
            f"Skipping torch.compile: only {total_steps:,} total steps "
            f"(< {args.compile_min_steps}).",
            flush=True,
        )

    train_callable, compiled = maybe_compile(
        wrapper=wrapper,
        enabled=use_compile,
        mode=args.compile_mode,
    )

    # Static GPU addresses.
    x_gpu = torch.empty(
        (batch_size, model_config.max_seq_len),
        dtype=torch.long,
        device=device,
    )
    y_gpu = torch.empty_like(x_gpu)

    # Force first compile before stage timing.
    if compiled:
        print("Warming compiled graph...", flush=True)
        x_gpu.zero_()
        y_gpu.fill_(-100)
        y_gpu[:, -16:] = 0

        optimizer.zero_grad(set_to_none=True)

        with amp_context(amp_dtype):
            warm_loss = train_callable(x_gpu, y_gpu)

        scaler.scale(warm_loss).backward()
        optimizer.zero_grad(set_to_none=True)
        torch.cuda.synchronize()
        print("Compile warmup complete.", flush=True)

    start_stage = int(state["stage_index"])
    start_batch = int(state["batch_in_stage"])
    global_step = int(state["global_step"])
    real_rows_seen = int(state["real_rows_seen"])
    npc_rows_seen = int(state["npc_rows_seen"])
    replay_rows_seen = int(state["replay_rows_seen"])
    best_npc_loss = float(state["best_npc_loss"])
    best_balanced_score = float(state["best_balanced_score"])
    baseline_uo_loss = state.get("baseline_uo_loss")

    model.train()

    loss_samples: List[torch.Tensor] = []
    processed_rows_since_log = 0
    real_rows_since_log = 0
    log_started = time.perf_counter()

    for stage_index in range(start_stage, len(ratios)):
        ratio = ratios[stage_index]

        schedule = build_stage_schedule(
            stage_index=stage_index,
            npc_ratio=ratio,
            npc_count=npc_train.count,
            replay_num_starts=replay.num_starts,
            batch_size=batch_size,
            seed=args.seed + 50_000,
        )

        stage_start_batch = (
            start_batch
            if stage_index == start_stage
            else 0
        )

        print()
        print("=" * 78, flush=True)
        print(
            f"NPC STAGE {stage_index + 1}/{len(ratios)} | "
            f"{ratio * 100:.0f}% NPC / "
            f"{(1.0 - ratio) * 100:.0f}% UO replay | "
            f"one full NPC epoch",
            flush=True,
        )
        print(
            f"Starting batch {stage_start_batch:,}/{schedule.plan.batches:,}",
            flush=True,
        )
        print("=" * 78, flush=True)

        prefetcher = MixedBatchPrefetcher(
            schedule=schedule,
            npc_dataset=npc_train,
            replay_corpus=replay,
            seq_len=model_config.max_seq_len,
            batch_size=batch_size,
            start_batch=stage_start_batch,
            buffers=args.prefetch_buffers,
        )

        stage_npc_rows = 0
        stage_replay_rows = 0
        stage_real_rows = 0
        stage_started = time.perf_counter()

        for batch in prefetcher:
            lr = learning_rate_at_step(
                step=global_step,
                total_steps=total_steps,
                max_lr=args.lr,
                min_lr=args.min_lr,
                warmup_fraction=args.warmup_fraction,
            )

            set_optimizer_lr(optimizer, lr)

            x_gpu.copy_(batch.x_cpu, non_blocking=False)
            y_gpu.copy_(batch.y_cpu, non_blocking=False)
            prefetcher.release(batch)

            optimizer.zero_grad(set_to_none=True)

            with amp_context(amp_dtype):
                loss = train_callable(x_gpu, y_gpu)

            scaler.scale(loss).backward()
            scaler.unscale_(optimizer)

            torch.nn.utils.clip_grad_norm_(
                model.parameters(),
                max_norm=args.grad_clip,
                foreach=True,
            )

            scaler.step(optimizer)
            scaler.update()

            loss_samples.append(loss.detach())

            global_step += 1
            real_rows_seen += batch.real_sequences
            npc_rows_seen += batch.npc_sequences
            replay_rows_seen += batch.replay_sequences

            stage_real_rows += batch.real_sequences
            stage_npc_rows += batch.npc_sequences
            stage_replay_rows += batch.replay_sequences

            processed_rows_since_log += batch_size
            real_rows_since_log += batch.real_sequences

            next_batch = batch.batch_index + 1

            if global_step % args.log_every == 0:
                torch.cuda.synchronize()
                now = time.perf_counter()
                interval = max(1e-9, now - log_started)

                mean_loss = float(
                    torch.stack(loss_samples).mean().item()
                )

                if not math.isfinite(mean_loss):
                    raise FloatingPointError(
                        f"non-finite loss at global step {global_step}"
                    )

                progress = (
                    100.0
                    * next_batch
                    / schedule.plan.batches
                )

                gpu_tokens = (
                    processed_rows_since_log
                    * model_config.max_seq_len
                )

                real_tokens = (
                    real_rows_since_log
                    * model_config.max_seq_len
                )

                print(
                    f"stage={stage_index + 1}/{len(ratios)} "
                    f"mix={ratio * 100:.0f}%NPC "
                    f"batch={next_batch:,}/{schedule.plan.batches:,} "
                    f"({progress:5.1f}%) "
                    f"global={global_step:,}/{total_steps:,} "
                    f"loss={mean_loss:.4f} "
                    f"lr={lr:.2e} "
                    f"gpu_tok/s={gpu_tokens / interval:,.0f} "
                    f"real_tok/s={real_tokens / interval:,.0f}",
                    flush=True,
                )

                loss_samples.clear()
                processed_rows_since_log = 0
                real_rows_since_log = 0
                log_started = now

            if (
                args.checkpoint_every > 0
                and global_step % args.checkpoint_every == 0
            ):
                torch.cuda.synchronize()

                checkpoint_state = {
                    "stage_index": stage_index,
                    "batch_in_stage": next_batch,
                    "global_step": global_step,
                    "real_rows_seen": real_rows_seen,
                    "npc_rows_seen": npc_rows_seen,
                    "replay_rows_seen": replay_rows_seen,
                    "best_npc_loss": best_npc_loss,
                    "best_balanced_score": best_balanced_score,
                    "baseline_uo_loss": baseline_uo_loss,
                }

                print(
                    f"Saving resume checkpoint at step {global_step:,}...",
                    flush=True,
                )

                save_checkpoint(
                    path=latest_path,
                    model=model,
                    optimizer=optimizer,
                    scaler=scaler,
                    state=checkpoint_state,
                    model_config=model_config,
                    training_config=training_config,
                    history=history,
                )

                copy_backup(latest_path, args.backup_dir)

        torch.cuda.synchronize()
        stage_elapsed = max(1e-9, time.perf_counter() - stage_started)
        actual_ratio = stage_npc_rows / max(1, stage_real_rows)

        print()
        print(
            f"Stage {stage_index + 1} complete: "
            f"NPC rows={stage_npc_rows:,} | "
            f"replay rows={stage_replay_rows:,} | "
            f"actual NPC={actual_ratio * 100:.3f}% | "
            f"real tok/s={stage_real_rows * model_config.max_seq_len / stage_elapsed:,.0f}",
            flush=True,
        )

        print("Validation:", flush=True)

        npc_metrics = evaluate_npc(
            model=model,
            dataset=npc_val,
            batch_size=min(args.val_batch_size, batch_size),
            device=device,
            amp_dtype=amp_dtype,
            max_batches=args.npc_val_batches,
        )

        print(
            f"  NPC val: loss={npc_metrics['loss']:.4f} "
            f"ppl={npc_metrics['ppl']:.2f} "
            f"token_acc={npc_metrics['token_accuracy'] * 100:.2f}% "
            f"exact={npc_metrics['exact_accuracy'] * 100:.2f}%",
            flush=True,
        )

        task_line = " | ".join(
            f"{task}={npc_metrics['per_task_exact'][task] * 100:.1f}%"
            for task in TASKS
        )
        print(f"  NPC exact by task: {task_line}", flush=True)

        uo_metrics = None

        if uo_val is not None:
            uo_metrics = evaluate_lm_corpus(
                model=model,
                corpus=uo_val,
                batch_size=min(args.val_batch_size, batch_size),
                max_batches=args.uo_val_batches,
                device=device,
                amp_dtype=amp_dtype,
            )

            print(
                f"  UO story val: loss={uo_metrics['loss']:.4f} "
                f"ppl={uo_metrics['ppl']:.3f}",
                flush=True,
            )

        tiny_metrics = None

        if tiny_val is not None:
            tiny_metrics = evaluate_lm_corpus(
                model=model,
                corpus=tiny_val,
                batch_size=min(args.val_batch_size, batch_size),
                max_batches=args.tiny_val_batches,
                device=device,
                amp_dtype=amp_dtype,
            )

            print(
                f"  TinyStories val: loss={tiny_metrics['loss']:.4f} "
                f"ppl={tiny_metrics['ppl']:.3f}",
                flush=True,
            )

        geometry = model.geometry_gain_summary()

        balanced_score = float(npc_metrics["loss"])

        if (
            uo_metrics is not None
            and baseline_uo_loss is not None
        ):
            forgetting = max(
                0.0,
                float(uo_metrics["loss"])
                - float(baseline_uo_loss),
            )
            balanced_score += args.forgetting_penalty * forgetting

        stage_record = {
            "event": "stage_complete",
            "stage_index": stage_index,
            "stage_number": stage_index + 1,
            "target_npc_ratio": ratio,
            "actual_npc_ratio": actual_ratio,
            "global_step": global_step,
            "npc_validation": npc_metrics,
            "uo_validation": uo_metrics,
            "tiny_validation": tiny_metrics,
            "balanced_score": balanced_score,
            "geometry": geometry,
        }

        history.append(stage_record)

        history_path.write_text(
            json.dumps(history, indent=2),
            encoding="utf-8",
        )

        next_state = {
            "stage_index": stage_index + 1,
            "batch_in_stage": 0,
            "global_step": global_step,
            "real_rows_seen": real_rows_seen,
            "npc_rows_seen": npc_rows_seen,
            "replay_rows_seen": replay_rows_seen,
            "best_npc_loss": best_npc_loss,
            "best_balanced_score": best_balanced_score,
            "baseline_uo_loss": baseline_uo_loss,
        }

        stage_pct = int(round(ratio * 100))
        stage_path = checkpoint_dir / (
            f"stage_{stage_index + 1}_{stage_pct}pct_npc.pt"
        )

        if float(npc_metrics["loss"]) < best_npc_loss:
            best_npc_loss = float(npc_metrics["loss"])
            next_state["best_npc_loss"] = best_npc_loss

            print(
                f"New best NPC validation loss {best_npc_loss:.4f}; "
                f"saving {best_npc_path.name}",
                flush=True,
            )

            save_checkpoint(
                path=best_npc_path,
                model=model,
                optimizer=optimizer,
                scaler=scaler,
                state=next_state,
                model_config=model_config,
                training_config=training_config,
                history=history,
            )

            copy_backup(best_npc_path, args.backup_dir)

        if balanced_score < best_balanced_score:
            best_balanced_score = balanced_score
            next_state["best_balanced_score"] = best_balanced_score

            print(
                f"New best balanced score {best_balanced_score:.4f}; "
                f"saving {best_balanced_path.name}",
                flush=True,
            )

            save_checkpoint(
                path=best_balanced_path,
                model=model,
                optimizer=optimizer,
                scaler=scaler,
                state=next_state,
                model_config=model_config,
                training_config=training_config,
                history=history,
            )

            copy_backup(best_balanced_path, args.backup_dir)

        save_checkpoint(
            path=stage_path,
            model=model,
            optimizer=optimizer,
            scaler=scaler,
            state=next_state,
            model_config=model_config,
            training_config=training_config,
            history=history,
        )

        save_checkpoint(
            path=latest_path,
            model=model,
            optimizer=optimizer,
            scaler=scaler,
            state=next_state,
            model_config=model_config,
            training_config=training_config,
            history=history,
        )

        copy_backup(stage_path, args.backup_dir)
        copy_backup(latest_path, args.backup_dir)

        start_batch = 0

    final_state = {
        "stage_index": len(ratios),
        "batch_in_stage": 0,
        "global_step": global_step,
        "real_rows_seen": real_rows_seen,
        "npc_rows_seen": npc_rows_seen,
        "replay_rows_seen": replay_rows_seen,
        "best_npc_loss": best_npc_loss,
        "best_balanced_score": best_balanced_score,
        "baseline_uo_loss": baseline_uo_loss,
    }

    save_checkpoint(
        path=final_path,
        model=model,
        optimizer=optimizer,
        scaler=scaler,
        state=final_state,
        model_config=model_config,
        training_config=training_config,
        history=history,
    )

    copy_backup(final_path, args.backup_dir)

    summary = {
        "source_checkpoint": str(source_checkpoint),
        "model_config": asdict(model_config),
        "training_config": training_config,
        "final_state": final_state,
        "geometry": model.geometry_gain_summary(),
        "history_file": str(history_path),
        "best_npc_checkpoint": str(best_npc_path) if best_npc_path.exists() else None,
        "best_balanced_checkpoint": str(best_balanced_path) if best_balanced_path.exists() else None,
        "final_checkpoint": str(final_path),
    }

    summary_path = output_dir / "training_summary.json"
    summary_path.write_text(
        json.dumps(summary, indent=2),
        encoding="utf-8",
    )

    print()
    print("=" * 78, flush=True)
    print("NPC BEHAVIOR TRAINING COMPLETE", flush=True)
    print("=" * 78, flush=True)
    print(f"global steps:       {global_step:,}", flush=True)
    print(f"NPC rows seen:      {npc_rows_seen:,}", flush=True)
    print(f"UO replay rows:     {replay_rows_seen:,}", flush=True)
    print(f"best NPC:           {best_npc_path}", flush=True)
    print(f"best balanced:      {best_balanced_path}", flush=True)
    print(f"final:              {final_path}", flush=True)
    print(f"history:            {history_path}", flush=True)

    return summary


