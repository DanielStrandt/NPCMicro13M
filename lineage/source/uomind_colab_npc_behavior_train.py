                    train_labels=str(cached["train_labels"]),
                    train_tasks=str(cached["train_tasks"]),
                    validation_inputs=str(cached["validation_inputs"]),
                    validation_labels=str(cached["validation_labels"]),
                    validation_tasks=str(cached["validation_tasks"]),
                    rejected_too_long=int(cached["rejected_too_long"]),
