def build_optimizer(
    model: UOMindLM,
    lr: float,
    weight_decay: float,
) -> torch.optim.Optimizer:
    groups = model.parameter_groups(weight_decay)

    try:
        optimizer = torch.optim.AdamW(
            groups,
            lr=lr,
            betas=(0.9, 0.95),
            eps=1e-8,
            fused=True,
        )
        print("Optimizer: fused AdamW", flush=True)
        return optimizer
    except Exception as exc:
        print(
            f"Fused AdamW unavailable ({type(exc).__name__}); using foreach AdamW.",
            flush=True,
        )
        return torch.optim.AdamW(
            groups,
            lr=lr,
            betas=(0.9, 0.95),
            eps=1e-8,
            foreach=True,
        )


def learning_rate_at_step(
    step: int,
    total_steps: int,
    max_lr: float,
    min_lr: float,
    warmup_fraction: float,
) -> float:
    warmup_steps = max(
        10,
        int(total_steps * warmup_fraction),
    )

    warmup_steps = min(
        warmup_steps,
        max(1, total_steps // 4),
    )

    if step < warmup_steps:
        return max_lr * (step + 1) / warmup_steps

    progress = (
        step - warmup_steps
    ) / max(1, total_steps - warmup_steps)

    progress = min(1.0, max(0.0, progress))
    cosine = 0.5 * (1.0 + math.cos(math.pi * progress))

    return min_lr + (max_lr - min_lr) * cosine


def set_optimizer_lr(
    optimizer: torch.optim.Optimizer,
    lr: float,
) -> None:
    for group in optimizer.param_groups:
        group["lr"] = lr


def recursive_to_cpu(value):
    if torch.is_tensor(value):
        return value.detach().cpu()

    if isinstance(value, dict):
        return {
            key: recursive_to_cpu(item)
            for key, item in value.items()
        }

    if isinstance(value, list):
        return [recursive_to_cpu(item) for item in value]

    if isinstance(value, tuple):
        return tuple(recursive_to_cpu(item) for item in value)

    return value


def optimizer_to_device(
    optimizer: torch.optim.Optimizer,
    device: torch.device,
) -> None:
    for state in optimizer.state.values():
        for key, value in list(state.items()):
            if torch.is_tensor(value):
                state[key] = value.to(device)


def save_checkpoint(
    *,
    path: Path,
    model: UOMindLM,
    optimizer: torch.optim.Optimizer,
    scaler,
    state: Dict[str, object],
    model_config: ModelConfig,
    training_config: Dict[str, object],
    history: List[Dict[str, object]],
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + ".tmp")

    payload = {
        "model_state_dict": recursive_to_cpu(model.state_dict()),
        "optimizer_state_dict": recursive_to_cpu(optimizer.state_dict()),
        "scaler_state_dict": scaler.state_dict(),
        "state": state,
        "model_config": asdict(model_config),
        "training_config": training_config,
        "history": history,
        "control_map": {
            "actions": ACTION_TOKENS,
            "tones": TONE_TOKENS,
        },
        "rng": {
            "python": random.getstate(),
            "numpy": np.random.get_state(),
            "torch": torch.get_rng_state(),
            "cuda": torch.cuda.get_rng_state_all(),
        },
    }

    torch.save(payload, temp)
    temp.replace(path)


def restore_rng(payload: Dict[str, object]) -> None:
    rng = payload.get("rng")

    if not rng:
        return

    try:
        random.setstate(rng["python"])
        np.random.set_state(rng["numpy"])
        torch.set_rng_state(rng["torch"])
        torch.cuda.set_rng_state_all(rng["cuda"])
    except Exception:
        pass


def copy_backup(source: Path, backup_dir: str) -> None:
    if not backup_dir:
        return

    destination = Path(backup_dir)
    destination.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination / source.name)


