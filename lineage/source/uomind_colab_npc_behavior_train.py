class ScenarioGenerator:
    def __init__(self, seed: int) -> None:
        self.rng = random.Random(seed)

    def choice(self, values: Sequence):
        return self.rng.choice(values)

    def randint(self, low: int, high: int) -> int:
        return self.rng.randint(low, high)

    def coin(self, p: float = 0.5) -> bool:
        return self.rng.random() < p

    def shuffled_fields(self, fields: Sequence[str]) -> str:
        fields = list(fields)
        self.rng.shuffle(fields)
        return ";".join(fields)

    def common(self, role: str) -> Tuple[str, str, str, str, int]:
        name = self.choice(NAMES)
        location = self.choice(LOCATIONS)
        persona = self.choice(PERSONAS)
        voice = self.choice(VOICES)
        relation = self.randint(-2, 2)
        return name, location, persona, voice, relation

    def tone_for(
        self,
        action: str,
        persona: str,
        fear: int = 0,
    ) -> str:
        if action == "FLEE" or (
            action == "DEFLECT" and fear >= 2
        ):
            return "AFRAID"

        if action in {
            "CALL_GUARDS",
            "ACCUSE",
            "ASK_LEAVE",
            "REPORT",
        }:
            return "ANGRY"

        if persona == "dutiful" or action in {
            "ADMIT",
            "OFFER_QUEST",
            "COMPLETE_QUEST",
            "PAY_REWARD",
        }:
            return "FORMAL"

        if persona == "gruff" or action == "COUNTER":
            return "GRUFF"

        if persona in {"kind", "jovial"} or action in {
            "ACCEPT",
            "HELP",
            "TREAT",
            "SHARE",
            "SERVE",
        }:
            return "WARM"

        return "WARY"

    def format_example(
        self,
        *,
        task: str,
        role: str,
        name: str,
        location: str,
        persona: str,
        voice: str,
        relation: int,
        state_fields: Sequence[str],
        memory: str,
        player: str,
        action: str,
        speech: str,
        fear: int = 0,
    ) -> NPCExample:
        tone = self.tone_for(
            action=action,
            persona=persona,
            fear=fear,
        )

        state = self.shuffled_fields(
            [
                f"task={task}",
                f"role={role}",
                f"voice={voice}",
                *state_fields,
            ]
        )

        prompt = (
            f"<BOS> <NPC> {name} "
            f"<LOCATION> {location} "
            f"<MOOD> {persona} "
            f"<REL> {relation} "
            f"<STATE> {state} "
            f"<MEMORY> {memory} "
            f"<PLAYER> \"{player}\" "
            f"<ACTION>"
        )

        target = (
            f"{ACTION_TOKENS[action]} "
            f"<TONE> {TONE_TOKENS[tone]} "
            f"<SAY> {speech} <EOS>"
        )

        return NPCExample(
            prompt=prompt,
            target=target,
            task=task,
            action=action,
            tone=tone,
        )

