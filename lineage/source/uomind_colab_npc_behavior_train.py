def initialize_control_embeddings(
    model: UOMindLM,
    tokenizer: Tokenizer,
) -> None:
    """
    Seed reserved control-token embeddings from their natural-language labels.

    The <Rxx> rows were deliberately reserved during pretraining and normally
    received almost no corpus exposure. Copying the mean pretrained embedding
    of the label words gives them a useful semantic starting direction while
    preserving the rest of the checkpoint exactly.
    """

    with torch.no_grad():
        weight = model.token_embedding.weight

        for control_token, meaning in CONTROL_TOKEN_MEANINGS.items():
            control_id = tokenizer.token_to_id(control_token)

            if control_id is None:
                continue

            text = meaning.lower().replace("_", " ")
            ids = tokenizer.encode(text).ids

            ids = [
                token_id
                for token_id in ids
                if token_id != control_id
            ]

            if not ids:
                continue

            source = weight[
                torch.tensor(
                    ids,
                    dtype=torch.long,
                    device=weight.device,
                )
            ].mean(dim=0)

            weight[control_id].copy_(source)

