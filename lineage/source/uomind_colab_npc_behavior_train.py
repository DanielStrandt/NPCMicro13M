def encode_npc_example(
    example: NPCExample,
    tokenizer: Tokenizer,
    seq_len: int,
) -> Optional[Tuple[np.ndarray, np.ndarray, int]]:
    pad_id = tokenizer.token_to_id("<PAD>")

    if pad_id is None:
        raise RuntimeError("<PAD> missing")

    prompt_ids = tokenizer.encode(example.prompt).ids
    target_ids = tokenizer.encode(example.target).ids

    full = prompt_ids + target_ids

    # Need at most T+1 tokens so x=full[:-1], y=full[1:] fit T.
    if len(full) > seq_len + 1:
        return None

    if len(prompt_ids) < 1 or len(target_ids) < 1:
        return None

    x = np.full(
        (seq_len,),
        pad_id,
        dtype=np.uint16,
    )

    y = np.full(
        (seq_len,),
        -100,
        dtype=np.int16,
    )

    input_ids = full[:-1]
    next_ids = full[1:]

    x[:len(input_ids)] = np.asarray(
        input_ids,
        dtype=np.uint16,
    )

    # If prompt length is P, input position P-1 contains <ACTION> and predicts
    # target token 0. Everything before P-1 is context-only and ignored.
    supervised_start = len(prompt_ids) - 1

    y[
        supervised_start:len(next_ids)
    ] = np.asarray(
        next_ids[supervised_start:],
        dtype=np.int16,
    )

    task_id = TASK_TO_ID[example.task]

    return x, y, task_id


def dataset_fingerprint(
    tokenizer_path: Path,
    train_examples: int,
    validation_examples: int,
    seed: int,
) -> str:
    payload = {
        "tokenizer_sha256": sha256_file(tokenizer_path),
        "train_examples": train_examples,
        "validation_examples": validation_examples,
        "seed": seed,
        "generator_version": 3,
        "tasks": TASKS,
        "actions": ACTION_TOKENS,
        "tones": TONE_TOKENS,
    }

    return hashlib.sha256(
        json.dumps(
            payload,
            sort_keys=True,
        ).encode("utf-8")
    ).hexdigest()


def create_split_arrays(
    *,
    split: str,
    count: int,
    seed: int,
    tokenizer: Tokenizer,
    seq_len: int,
    output_dir: Path,
    batch_generate: int,
    preview_handle,
) -> Tuple[Path, Path, Path, int]:
    input_path = output_dir / f"npc_{split}_inputs.npy"
    label_path = output_dir / f"npc_{split}_labels.npy"
    task_path = output_dir / f"npc_{split}_tasks.npy"

    x_map = np.lib.format.open_memmap(
        input_path,
        mode="w+",
        dtype=np.uint16,
        shape=(count, seq_len),
    )

    y_map = np.lib.format.open_memmap(
        label_path,
        mode="w+",
        dtype=np.int16,
        shape=(count, seq_len),
    )

    task_map = np.lib.format.open_memmap(
        task_path,
        mode="w+",
        dtype=np.uint8,
        shape=(count,),
    )

    generator = ScenarioGenerator(seed)

    written = 0
    rejected = 0
    started = time.perf_counter()

    task_cursor = 0

    while written < count:
        target_batch = min(
            batch_generate,
            count - written,
        )

        candidates: List[NPCExample] = []

        # Oversample slightly so occasional over-length examples do not create
        # lots of small tokenizer calls.
        candidate_count = max(
            target_batch,
            int(target_batch * 1.08) + 8,
        )

        for _ in range(candidate_count):
            task = TASKS[
                task_cursor % len(TASKS)
            ]
            task_cursor += 1
            candidates.append(generator.generate(task))

        # Tokenizers' encode_batch is Rust-backed. Encoding prompt and target
        # separately preserves the exact loss boundary without parsing tokens.
        prompt_encodings = tokenizer.encode_batch(
            [example.prompt for example in candidates]
        )

        target_encodings = tokenizer.encode_batch(
            [example.target for example in candidates]
        )

        for example, prompt_encoding, target_encoding in zip(
            candidates,
            prompt_encodings,
            target_encodings,
        ):
            if written >= count:
                break

            prompt_ids = prompt_encoding.ids
            target_ids = target_encoding.ids
            full = prompt_ids + target_ids

            if len(full) > seq_len + 1:
                rejected += 1
                continue

            pad_id = tokenizer.token_to_id("<PAD>")

            x = np.full(
                (seq_len,),
                pad_id,
                dtype=np.uint16,
            )

            y = np.full(
                (seq_len,),
                -100,
                dtype=np.int16,
            )

            input_ids = full[:-1]
            next_ids = full[1:]

            x[:len(input_ids)] = np.asarray(
                input_ids,
                dtype=np.uint16,
            )

            supervised_start = len(prompt_ids) - 1

            y[
                supervised_start:len(next_ids)
            ] = np.asarray(
                next_ids[supervised_start:],
                dtype=np.int16,
            )

            x_map[written] = x
            y_map[written] = y
            task_map[written] = TASK_TO_ID[example.task]

            if written < 8 and preview_handle is not None:
                preview_handle.write(
                    f"[{split} {written}] TASK={example.task} "
                    f"ACTION={example.action} TONE={example.tone}\n"
                )
                preview_handle.write(example.prompt + "\n")
                preview_handle.write(example.target + "\n\n")

            written += 1

        if written == 1 or written % 20000 < batch_generate:
            elapsed = max(
                1e-9,
                time.perf_counter() - started,
            )

            print(
                f"  NPC {split}: {written:,}/{count:,} examples | "
                f"rejected_long={rejected:,} | "
                f"{written / elapsed:,.0f} ex/s",
                flush=True,
            )

    x_map.flush()
    y_map.flush()
    task_map.flush()

    del x_map, y_map, task_map
    gc.collect()

    return input_path, label_path, task_path, rejected


