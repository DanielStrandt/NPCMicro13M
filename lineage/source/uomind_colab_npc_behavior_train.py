@torch.inference_mode()
def evaluate_npc(
    *,
    model: UOMindLM,
    dataset: NPCArrayDataset,
    batch_size: int,
    device: torch.device,
    amp_dtype: torch.dtype,
    max_batches: int,
) -> Dict[str, object]:
    was_training = model.training
    model.eval()

    x_cpu = torch.empty(
        (batch_size, model.config.max_seq_len),
        dtype=torch.long,
        pin_memory=True,
    )

    y_cpu = torch.empty_like(x_cpu)
    x_np = x_cpu.numpy()
    y_np = y_cpu.numpy()

    x_gpu = torch.empty_like(x_cpu, device=device)
    y_gpu = torch.empty_like(y_cpu, device=device)

    total_loss = 0.0
    total_supervised = 0
    total_correct = 0
    exact_correct = 0
    exact_total = 0

    per_task_exact = np.zeros(len(TASKS), dtype=np.int64)
    per_task_total = np.zeros(len(TASKS), dtype=np.int64)

    batches = min(
        max_batches,
        math.ceil(dataset.count / batch_size),
    )

    started = time.perf_counter()

    for batch_index in range(batches):
        start = batch_index * batch_size
        end = min(start + batch_size, dataset.count)
        real = end - start

        x_np.fill(0)
        y_np.fill(-100)

        indices = np.arange(start, end, dtype=np.int64)
        rows = np.arange(real, dtype=np.int64)

        dataset.gather_into(
            indices=indices,
            x_dest=x_np,
            y_dest=y_np,
            rows=rows,
        )

        x_gpu.copy_(x_cpu, non_blocking=False)
        y_gpu.copy_(y_cpu, non_blocking=False)

        with amp_context(amp_dtype):
            logits = model(x_gpu)

            token_loss = F.cross_entropy(
                logits.reshape(-1, model.config.vocab_size),
                y_gpu.reshape(-1),
                ignore_index=-100,
                reduction="none",
            ).view_as(y_gpu)

        pred = logits.argmax(dim=-1)
        mask = y_gpu.ne(-100)

        supervised_count = int(mask[:real].sum().item())
        correct = int(
            ((pred[:real] == y_gpu[:real]) & mask[:real]).sum().item()
        )

        loss_sum = float(token_loss[:real].sum().item())

        row_exact = (
            (~mask[:real])
            | pred[:real].eq(y_gpu[:real])
        ).all(dim=1)

        row_exact_cpu = row_exact.detach().cpu().numpy().astype(np.bool_)
        task_ids = np.asarray(dataset.tasks[start:end], dtype=np.int64)

        total_loss += loss_sum
        total_supervised += supervised_count
        total_correct += correct
        exact_correct += int(row_exact_cpu.sum())
        exact_total += real

        for task_id in range(len(TASKS)):
            task_mask = task_ids == task_id

            if task_mask.any():
                per_task_total[task_id] += int(task_mask.sum())
                per_task_exact[task_id] += int(row_exact_cpu[task_mask].sum())

    torch.cuda.synchronize()
    elapsed = max(1e-9, time.perf_counter() - started)

    if was_training:
        model.train()

    mean_loss = total_loss / max(1, total_supervised)

    return {
        "loss": mean_loss,
        "ppl": math.exp(min(mean_loss, 20.0)),
        "token_accuracy": total_correct / max(1, total_supervised),
        "exact_accuracy": exact_correct / max(1, exact_total),
        "examples": exact_total,
        "tok_per_sec": total_supervised / elapsed,
        "per_task_exact": {
            task: (
                float(per_task_exact[task_id])
                / max(1, int(per_task_total[task_id]))
            )
            for task_id, task in enumerate(TASKS)
        },
    }


@torch.inference_mode()
def evaluate_lm_corpus(
    *,
    model: UOMindLM,
    corpus: FixedBlockCorpus,
    batch_size: int,
    max_batches: int,
    device: torch.device,
    amp_dtype: torch.dtype,
) -> Dict[str, float]:
    was_training = model.training
    model.eval()

    x_cpu = torch.empty(
        (batch_size, model.config.max_seq_len),
        dtype=torch.long,
        pin_memory=True,
    )
    y_cpu = torch.empty_like(x_cpu)
    x_np = x_cpu.numpy()
    y_np = y_cpu.numpy()

    x_gpu = torch.empty_like(x_cpu, device=device)
    y_gpu = torch.empty_like(y_cpu, device=device)

    losses: List[torch.Tensor] = []
    token_count = 0

    batches = min(
        max_batches,
        math.ceil(corpus.num_blocks / batch_size),
    )

    for batch_index in range(batches):
        start = batch_index * batch_size
        end = min(start + batch_size, corpus.num_blocks)
        real = end - start

        x_np.fill(0)
        y_np.fill(-100)

        indices = np.arange(start, end, dtype=np.int64)
        rows = np.arange(real, dtype=np.int64)

        corpus.gather_into(
            indices=indices,
            x_dest=x_np,
            y_dest=y_np,
            rows=rows,
        )

        x_gpu.copy_(x_cpu, non_blocking=False)
        y_gpu.copy_(y_cpu, non_blocking=False)

        with amp_context(amp_dtype):
            logits = model(x_gpu)
            loss = F.cross_entropy(
                logits.reshape(-1, model.config.vocab_size),
                y_gpu.reshape(-1),
                ignore_index=-100,
            )

        losses.append(loss.detach())
        token_count += real * model.config.max_seq_len

    torch.cuda.synchronize()

    mean_loss = float(torch.stack(losses).mean().item())

    if was_training:
        model.train()

    return {
        "loss": mean_loss,
        "ppl": math.exp(min(mean_loss, 20.0)),
        "tokens": token_count,
    }


