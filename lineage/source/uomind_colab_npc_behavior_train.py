    tokenizer = Tokenizer.from_file(str(tokenizer_path))
    validate_tokenizer_controls(tokenizer)

    model, _, model_config = load_model(
        checkpoint_path=checkpoint_path,
        tokenizer=tokenizer,
        device=device,
    )

    (output_dir / "control_map.json").write_text(
        json.dumps(
            {
                "actions": ACTION_TOKENS,
                "tones": TONE_TOKENS,
                "token_meanings": CONTROL_TOKEN_MEANINGS,
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    npc_meta = prepare_npc_dataset(
        output_dir=output_dir,
        tokenizer=tokenizer,
        tokenizer_path=tokenizer_path,
        train_examples=args.train_examples,
        validation_examples=args.validation_examples,
        seq_len=model_config.max_seq_len,
        seed=args.seed,
        batch_generate=args.generation_batch,
    )

