def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)

    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def choose_amp_dtype() -> torch.dtype:
    if torch.cuda.is_bf16_supported():
        return torch.bfloat16
    return torch.float16


def amp_context(dtype: torch.dtype):
    return torch.autocast(
        device_type="cuda",
        dtype=dtype,
    )


def make_grad_scaler(dtype: torch.dtype):
    enabled = dtype == torch.float16

    try:
        return torch.amp.GradScaler(
            "cuda",
            enabled=enabled,
        )
    except Exception:
        return torch.cuda.amp.GradScaler(
            enabled=enabled,
        )


def gpu_memory_line() -> str:
    free, total = torch.cuda.mem_get_info()

    return (
        f"{free / 2**30:.2f} GiB free / "
        f"{total / 2**30:.2f} GiB total"
    )


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()

    with path.open("rb") as handle:
        while True:
            block = handle.read(8 * 1024 * 1024)

            if not block:
                break

            digest.update(block)

    return digest.hexdigest()


def parse_fractions(text: str) -> Tuple[float, ...]:
    values = tuple(
        float(part.strip())
        for part in text.split(",")
        if part.strip()
    )

    if not values:
        raise ValueError("no curriculum ratios supplied")

    for value in values:
        if not (0.0 < value <= 1.0):
            raise ValueError(
                f"ratios must be in (0,1], got {value}"
            )

    return values


