def validate_tokenizer_controls(tokenizer: Tokenizer) -> None:
    required = list(REQUIRED_MARKERS) + [
        f"<R{i:02d}>"
        for i in range(32)
    ]

    missing = [
        token
        for token in required
        if tokenizer.token_to_id(token) is None
    ]

    if missing:
        raise RuntimeError(
            "The tokenizer is missing reserved control tokens required by "
            f"this trainer: {missing}"
        )

    # Every control token should encode to exactly itself.
    bad = []

    for token in required:
        encoding = tokenizer.encode(token)
        token_id = tokenizer.token_to_id(token)

        if encoding.ids != [token_id]:
            bad.append(token)

    if bad:
        raise RuntimeError(
            "These control markers are not atomic tokenizer tokens: "
            f"{bad}"
        )


def load_model(
    checkpoint_path: Path,
    tokenizer: Tokenizer,
    device: torch.device,
) -> Tuple[UOMindLM, Dict[str, object], ModelConfig]:
    print(
        f"Loading UO-domain checkpoint: {checkpoint_path}",
        flush=True,
    )

    payload = torch.load(
        checkpoint_path,
        map_location="cpu",
        weights_only=False,
    )

    if "model_config" not in payload:
        raise RuntimeError("checkpoint has no model_config")

    config = ModelConfig(**dict(payload["model_config"]))

    if tokenizer.get_vocab_size() != config.vocab_size:
        raise RuntimeError(
            f"vocab mismatch: tokenizer={tokenizer.get_vocab_size()} "
            f"model={config.vocab_size}"
        )

    model = UOMindLM(config)

    state_dict = payload.get("model_state_dict")

    if state_dict is None:
        raise RuntimeError("checkpoint has no model_state_dict")

    incompatible = model.load_state_dict(
        state_dict,
        strict=False,
    )

    missing = [
        key
        for key in incompatible.missing_keys
        if "causal_bias" not in key
    ]

    if missing or incompatible.unexpected_keys:
        raise RuntimeError(
            "checkpoint/model mismatch: "
            f"missing={missing} "
            f"unexpected={list(incompatible.unexpected_keys)}"
        )

    model = model.to(device)

    print(
        f"Loaded {model.num_parameters():,} parameters; "
        f"geometry gain mean={model.geometry_gain_summary()['mean']:.4f}",
        flush=True,
    )

    return model, payload, config


