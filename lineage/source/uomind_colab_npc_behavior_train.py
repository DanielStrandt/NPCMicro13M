@dataclass
class PreparedBatch:
    buffer_id: int
    x_cpu: torch.Tensor
    y_cpu: torch.Tensor
    real_sequences: int
    npc_sequences: int
    replay_sequences: int
    batch_index: int


class MixedBatchPrefetcher:
    def __init__(
        self,
        *,
        schedule: StageSchedule,
        npc_dataset: NPCArrayDataset,
        replay_corpus: RandomWindowCorpus,
        seq_len: int,
        batch_size: int,
        start_batch: int,
        buffers: int,
    ) -> None:
        self.schedule = schedule
        self.npc_dataset = npc_dataset
        self.replay_corpus = replay_corpus
        self.seq_len = seq_len
        self.batch_size = batch_size
        self.start_batch = start_batch
        self.buffer_count = max(2, int(buffers))

        self.buffers: List[
            Tuple[torch.Tensor, torch.Tensor, np.ndarray, np.ndarray]
        ] = []

        for _ in range(self.buffer_count):
            x = torch.empty(
                (batch_size, seq_len),
                dtype=torch.long,
                pin_memory=True,
            )

            y = torch.empty_like(x)

            self.buffers.append(
                (
                    x,
                    y,
                    x.numpy(),
                    y.numpy(),
                )
            )

        self.free_queue: queue.Queue = queue.Queue()
        self.ready_queue: queue.Queue = queue.Queue(maxsize=self.buffer_count)

        for buffer_id in range(self.buffer_count):
            self.free_queue.put(buffer_id)

        self.error: Optional[BaseException] = None

        self.thread = threading.Thread(
            target=self._worker,
            daemon=True,
            name="npc-mixed-prefetch",
        )

        self.thread.start()

    def _worker(self) -> None:
        try:
            for batch_index in range(
                self.start_batch,
                self.schedule.plan.batches,
            ):
                buffer_id = self.free_queue.get()

                x_cpu, y_cpu, x_np, y_np = self.buffers[buffer_id]

                x_np.fill(0)
                y_np.fill(-100)

                domains, indices = self.schedule.batch_slice(batch_index)
                real_count = len(domains)

                rows = np.arange(real_count, dtype=np.int64)
                npc_rows = rows[domains == 1]
                replay_rows = rows[domains == 0]

                if npc_rows.size:
                    self.npc_dataset.gather_into(
                        indices=indices[domains == 1],
                        x_dest=x_np,
                        y_dest=y_np,
                        rows=npc_rows,
                    )

                if replay_rows.size:
                    self.replay_corpus.gather_into(
                        starts=indices[domains == 0],
                        x_dest=x_np,
                        y_dest=y_np,
                        rows=replay_rows,
                    )

                self.ready_queue.put(
                    PreparedBatch(
                        buffer_id=buffer_id,
                        x_cpu=x_cpu,
                        y_cpu=y_cpu,
                        real_sequences=real_count,
                        npc_sequences=int(npc_rows.size),
                        replay_sequences=int(replay_rows.size),
                        batch_index=batch_index,
                    )
                )

            self.ready_queue.put(None)

        except BaseException as exc:
            self.error = exc
            self.ready_queue.put(None)

    def __iter__(self) -> Iterator[PreparedBatch]:
        while True:
            item = self.ready_queue.get()

            if item is None:
                if self.error is not None:
                    raise self.error
                break

            yield item

    def release(self, batch: PreparedBatch) -> None:
        self.free_queue.put(batch.buffer_id)


